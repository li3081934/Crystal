/**
 * 生成"给 078 骷髅加装备"的图生图提示词（纯文本，UTF-8 写出）。
 * 用脚本拼提示词可以避免在 shell heredoc 里写中文时的编码乱码问题。
 *
 * 用法:
 *   node Web/tools/make-sheet-prompt.mjs --w 928 --h 2144 --cols 4 --frames "4 帧" \
 *        --action "站立" --out docs/art/petboon/prompt-078-stand.txt
 */
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const get = (name, def = null) => {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1] : def;
};

const w = get('--w');
const h = get('--h');
const cols = get('--cols');
const frames = get('--frames', '');
const action = get('--action', '');
const out = get('--out');

if (!w || !h || !cols || !out) {
  console.error('用法: node Web/tools/make-sheet-prompt.mjs --w 928 --h 2144 --cols 4 --frames "4 帧" --action "站立" --out <文件>');
  process.exit(1);
}

