  '2. 每一格必须保留输入里那一帧骷髅的轮廓、姿势、朝向、四肢位置和脚底位置；只做加法：在原图已有的像素上叠加新装备，不要覆盖、不要重画、不要改比例、不要改画风、不要改像素颗粒大小。',
