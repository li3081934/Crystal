  '4. 行与方向的对应关系（从上到下），每一行头盔的朝向都必须与该行骷髅身体的朝向严格一致：',
  '   第 1 行 = 正上方：人物背对镜头，只能看到后脑、后颈与护颈，绝对不能画出脸、眼缝、牙齿、面甲。',
